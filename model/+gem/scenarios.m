function list = scenarios(set)
%SCENARIOS The named catalogue of regression scenarios.
%   LIST = GEM.SCENARIOS() returns every scenario as a struct array with
%   .name, .direction, .frozen and .build (a zero-argument function handle).
%   LIST = GEM.SCENARIOS('frozen') or ('random') filters.
%
%   Each entry is one row of verification_plan.md, and the .covers field names
%   the requirements it traces to, so the plan can be generated from this file
%   rather than maintained beside it and allowed to drift.
%
%   FROZEN vs RANDOM, and why the repository holds only one of them:
%
%     frozen  -- small, directed, one scenario per behaviour. These are the
%                evidence behind the traceability table, so their vectors are
%                committed: a reviewer can read them, and a regression can run
%                without MATLAB installed.
%     random  -- large seeded sweeps. Regenerated by `make vectors` from the
%                seed in their manifest, and git-ignored, because the build can
%                reproduce them exactly and committed megabytes of generated
%                hex is precisely what the "authored vs generated" rule exists
%                to prevent.
%
%   See also GEM.GENSCENARIO, GEM.GENTXSCENARIO, GEM.WRITEVECTORS.

arguments
    set (1,:) char {mustBeMember(set, {'all','frozen','random'})} = 'all'
end

p = gem.params();

list = struct('name', {}, 'direction', {}, 'frozen', {}, 'covers', {}, ...
              'description', {}, 'build', {});

add = @(varargin) struct('name', varargin{1}, 'direction', varargin{2}, ...
    'frozen', varargin{3}, 'covers', {varargin{4}}, ...
    'description', varargin{5}, 'build', varargin{6});

% ---- frozen, directed: RX ------------------------------------------------

list(end+1) = add('rx_clean_sweep', 'rx', true, ...
    {'R8','R9','R13'}, ...
    'Good frames across the B.4 boundary length set, nominal gap and preamble.', ...
    @() gem.genScenario('rx_clean_sweep', NumFrames=12, ...
        Corruptions={'none'}, GapMode='nominal', PreambleMode='full'));

list(end+1) = add('rx_trimmed_preamble', 'rx', true, ...
    {'R8'}, ...
    'Preamble lengths 0..7, including SFD-only, which R8 must tolerate.', ...
    @() gem.genScenario('rx_trimmed_preamble', NumFrames=16, ...
        Corruptions={'none'}, GapMode='nominal', PreambleMode='random'));

list(end+1) = add('rx_min_gap', 'rx', true, ...
    {'R8','R10','R18'}, ...
    ['Minimum-size frames at the 8-byte gap floor Table 4-2 Note 3 permits ' ...
     '-- the tightest RX recovery case a compliant link can present.'], ...
    @() gem.genScenario('rx_min_gap', NumFrames=24, ...
        Lengths=[1 46], Corruptions={'none'}, GapMode='min', ...
        PreambleMode='none'));

list(end+1) = add('rx_bad_fcs', 'rx', true, ...
    {'R9','R10','R17'}, ...
    'Single-bit FCS corruption alternating with good frames.', ...
    @() gem.genScenario('rx_bad_fcs', NumFrames=16, ...
        Corruptions={'none','badfcs'}, GapMode='nominal'));

list(end+1) = add('rx_runt', 'rx', true, ...
    {'R10','R17'}, ...
    'Truncated frames -- also the case that exercises class precedence.', ...
    @() gem.genScenario('rx_runt', NumFrames=16, ...
        Corruptions={'none','truncate'}, GapMode='nominal'));

list(end+1) = add('rx_oversize', 'rx', true, ...
    {'R10','R17'}, ...
    'Frames past maxBasicFrameSize, detectable mid-reception.', ...
    @() gem.genScenario('rx_oversize', NumFrames=12, ...
        Corruptions={'none','oversize'}, GapMode='nominal'));

list(end+1) = add('rx_rxer', 'rx', true, ...
    {'R10','R13','R17'}, ...
    'RX_ER asserted mid-frame with the FCS left intact.', ...
    @() gem.genScenario('rx_rxer', NumFrames=12, ...
        Corruptions={'none','rxer'}, GapMode='nominal'));

list(end+1) = add('rx_garbage', 'rx', true, ...
    {'R11'}, ...
    ['Inter-frame octets with DV low, seeded with 0xD5 so a hunter that ' ...
     'scans while DV is deasserted is caught.'], ...
    @() gem.genScenario('rx_garbage', NumFrames=12, ...
        Corruptions={'none'}, GapMode='nominal', GarbageRate=1.0));

list(end+1) = add('rx_bad_sfd', 'rx', true, ...
    {'R8','R11'}, ...
    'Damaged SFD; the model, not the generator, defines the expected outcome.', ...
    @() gem.genScenario('rx_bad_sfd', NumFrames=12, ...
        Corruptions={'none','badsfd'}, GapMode='nominal'));

list(end+1) = add('rx_recovery_mix', 'rx', true, ...
    {'R10','R17','R21'}, ...
    ['Every error class interleaved with good frames at the minimum gap. ' ...
     'R10 is not tested by a bad frame -- it is tested by the good frame ' ...
     'after one.'], ...
    @() gem.genScenario('rx_recovery_mix', NumFrames=40, ...
        Corruptions={'none','badfcs','none','truncate','none','rxer', ...
                     'none','oversize'}, ...
        GapMode='min', PreambleMode='random', GarbageRate=0.3));

% ---- frozen, directed: TX ------------------------------------------------

list(end+1) = add('tx_clean_sweep', 'tx', true, ...
    {'R1','R2','R4','R5','R13'}, ...
    'Frame assembly across the boundary length set, full preamble and IFG.', ...
    @() gem.genTxScenario('tx_clean_sweep', NumFrames=12, ReadyMode='always'));

list(end+1) = add('tx_padding', 'tx', true, ...
    {'R3'}, ...
    'Payloads either side of 46 octets, checking pad to the 64-octet minimum.', ...
    @() gem.genTxScenario('tx_padding', NumFrames=12, ...
        Lengths=[0 1 20 44 45 46 47 60], ReadyMode='always'));

list(end+1) = add('tx_reject_oversize', 'tx', true, ...
    {'R6'}, ...
    ['A 1501-octet payload the MAC must refuse -- the expected cycle stream ' ...
     'contains no frame for it, so a MAC that truncates and transmits fails.'], ...
    @() gem.genTxScenario('tx_reject_oversize', NumFrames=4, ...
        ReadyMode='always', IncludeOversize=true));

list(end+1) = add('tx_backpressure', 'tx', true, ...
    {'R7','R15'}, ...
    'tready deasserted between frames -- the gap the MAC can wait through.', ...
    @() gem.genTxScenario('tx_backpressure', NumFrames=12, ReadyMode='random'));

% B.4b. The stall the MAC cannot wait through: user logic stops mid-payload,
% and RGMII has no pause once TX_EN is high. Every third frame is aborted with
% TX_ER and an inverted FCS, interleaved with frames that must transmit
% normally -- because recovering cleanly after an abort is as much of R7 as the
% abort itself, and a scenario of nothing but aborts would not test it.
list(end+1) = add('tx_underrun', 'tx', true, ...
    {'R7','R15','R17'}, ...
    'User stalls mid-payload; frames abort per B.4b and the MAC recovers.', ...
    @() gem.genTxScenario('tx_underrun', NumFrames=12, ReadyMode='always', ...
        StallEvery=3, StallDepth=60, StallCycles=64));

% ---- random sweeps, regenerated not committed ----------------------------

list(end+1) = add('random_rx_sweep', 'rx', false, ...
    {'R8','R9','R10','R11','R17'}, ...
    'Long seeded RX sweep: every corruption crossed with the length set.', ...
    @() gem.genScenario('random_rx_sweep', NumFrames=600, ...
        Lengths=[1 20 45 46 47 63 64 65 100 256 512 1000 1499 1500], ...
        Corruptions={'none','none','badfcs','truncate','rxer','oversize', ...
                     'badsfd','none'}, ...
        GapMode='random', PreambleMode='random', GarbageRate=0.25));

list(end+1) = add('random_tx_sweep', 'tx', false, ...
    {'R1','R3','R5','R7'}, ...
    'Long seeded TX sweep across the full length range.', ...
    @() gem.genTxScenario('random_tx_sweep', NumFrames=600, ...
        Lengths=1:37:p.MAX_PAYLOAD_BYTES, ReadyMode='random'));

switch set
    case 'frozen', list = list([list.frozen]);
    case 'random', list = list(~[list.frozen]);
end
end
